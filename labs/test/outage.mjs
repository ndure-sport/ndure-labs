import fs from 'node:fs';
const B='http://localhost:8787', M='http://127.0.0.1:8788', LOG=process.argv[2];
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms));
const ctl=(j)=>fetch(M+'/__ctl',{method:'POST',body:JSON.stringify(j)});
const sched=()=>fetch(`${B}/cdn-cgi/handler/scheduled?cron=*/15+*+*+*+*`);
const mails=()=>fs.readFileSync(LOG,'utf8').trim().split('\n').map(JSON.parse).filter(x=>x.email).map(x=>x.email);
const C={ready:true,health:true,terms:true};
const email='outage'+Date.now()+'@test.dk';
await ctl({brevoDown:true});
const r=await fetch(B+'/api/checkout',{method:'POST',headers:{'content-type':'application/json','cf-connecting-ip':'10.250.0.9'},body:JSON.stringify({qty:3,later:true,partner:false,name:'Outage Rider',email,consents:C,turnstile:'human-ok'})});
const id=(await r.json()).url.split('/').pop();
const crypto=await import('node:crypto');
const body=JSON.stringify({type:'checkout.session.completed',data:{object:{metadata:{order_id:id},payment_status:'paid'}}});
const t=Math.floor(Date.now()/1000);
await fetch(B+'/api/stripe/webhook',{method:'POST',body,headers:{'stripe-signature':`t=${t},v1=${crypto.createHmac('sha256','whsec_localtest').update(`${t}.${body}`).digest('hex')}`}});
await sleep(1500); await sched(); await sleep(500);
console.log('while Brevo is down, payment emails sent:', mails().filter(m=>m.to===email).length);
await ctl({brevoDown:false});
await sched(); await sleep(500);
console.log('right after recovery (retry waits 2 min):', mails().filter(m=>m.to===email).length);
console.log('waiting 2.5 minutes for the retry…'); await sleep(150000);
await Promise.all([sched(),sched(),sched()]); await sleep(1500);
const got=mails().filter(m=>m.to===email);
console.log('after the retry window:', got.length, 'email(s):', got.map(m=>m.subject).join(' | '));
